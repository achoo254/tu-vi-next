/**
 * `pnpm brand:gen`: everything the platforms show of the brand, derived from the AI-drawn master icon
 * (brand/app-icon-master-1024.png) and brand.config.json, with the Chromium of @playwright/test:
 *
 * - brand/app-icon.svg and app-icon-maskable.svg: the master embedded as WebP (the maskable one full-bleed
 *   on the brand colour, artwork inside the 80% safe zone), the sources @achoo254/brand draws from;
 * - brand/generated/: web manifest, PNG icons, favicon.ico (writeBrandFiles);
 * - apps/web/public/brand-mark-96.webp: the header mark;
 * - apps/web/public/og-image.png: the 1200 × 630 link preview in the app's night-sky look: the home illustration's
 *   zodiac wheel (apps/web/src/art/illustrations/hero-1200.webp, AI-drawn with open models) beside the owl, the
 *   gold name and the description, which are drawn here as text in the app's own fonts (never by the AI).
 *
 * Run after changing the master or the brand, then commit the files.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { chromiumRenderer, writeBrandFiles } from '@achoo254/brand/build';
import { primaryOrigin } from '@achoo254/brand/hosts';
import { type Page, chromium } from '@playwright/test';
import { BRAND_GENERATED_DIR, BRAND_ROOT, MANIFEST_OPTIONS, OG_IMAGE, loadTuviBrand } from '../apps/web/vite-brand';

const MASTER = new URL('brand/app-icon-master-1024.png', BRAND_ROOT);
const OG_ART = new URL('apps/web/src/art/illustrations/hero-1200.webp', BRAND_ROOT);
const PUBLIC_DIR = new URL('apps/web/public/', BRAND_ROOT);
/** The night blue at the edge of the icon tile, behind the maskable icon so the artwork can sit inside the safe zone. */
const TILE = '#16203e';
const ICON_LICENCE = 'AI-generated with open models (FLUX.2 klein 4B; Apache-2.0) for the hoandat ecosystem; owned by hoandat, all rights reserved (not CC0)';

/** The master scaled to `size` px and encoded by the browser, as a data URL. */
async function encodeMaster(page: Page, masterDataUrl: string, size: number, type: 'image/webp' | 'image/png'): Promise<string> {
  return page.evaluate(
    async ({ src, size, type }) => {
      const image = new Image();
      image.src = src;
      await image.decode();
      const canvas = document.createElement('canvas');
      canvas.width = size;
      canvas.height = size;
      const context = canvas.getContext('2d');
      if (!context) throw new Error('no 2d context');
      context.imageSmoothingQuality = 'high';
      context.drawImage(image, 0, 0, size, size);
      return canvas.toDataURL(type, 0.92);
    },
    { src: masterDataUrl, size, type },
  );
}

const dataUrlBytes = (dataUrl: string): Buffer => Buffer.from(dataUrl.slice(dataUrl.indexOf(',') + 1), 'base64');

function iconSvg(webpDataUrl: string, appName: string): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><!-- ${appName} app icon: ${ICON_LICENCE}. Generated by pnpm brand:gen from brand/app-icon-master-1024.png. --><image width="1024" height="1024" href="${webpDataUrl}"/></svg>\n`;
}

function maskableSvg(webpDataUrl: string, background: string, appName: string): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><!-- Maskable ${appName} app icon: ${ICON_LICENCE}. Generated by pnpm brand:gen. --><rect width="1024" height="1024" fill="${background}"/><image x="102" y="102" width="820" height="820" href="${webpDataUrl}"/></svg>\n`;
}

/** The art panel on the right shows the wheel (the middle of the illustration); its left edge fades into the sky. */
const OG_ART_WIDTH = 640;
/** The night sky, moon-white text and astrologer's gold of the app (apps/web/src/ui/tokens.css). */
const OG_COLORS = { deep: '#05061a', violet: '#2a1c66', blue: '#0e2558', text: '#f4efe1', muted: '#b9b6d8', gold: '#ecc771', goldDeep: '#e2b453' };

const webRequire = createRequire(new URL('apps/web/package.json', BRAND_ROOT));

/** A @fontsource weight stylesheet with its WOFF2 files inlined (WOFF fallbacks dropped), so the page renders offline. */
function inlinedFontCss(stylesheet: string): string {
  const file = webRequire.resolve(stylesheet);
  return readFileSync(file, 'utf8').replace(/url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\)(, url\([^)]+\) format\('woff'\))?/g, (_match, name: string) => {
    const bytes = readFileSync(new URL(`files/${name}`, pathToFileURL(file)));
    return `url(data:font/woff2;base64,${bytes.toString('base64')}) format('woff2')`;
  });
}

/** Small stars scattered over the sky: [left %, top %, size px, opacity]. */
const STARS: readonly (readonly [number, number, number, number])[] = [
  [6, 9, 2, 0.8], [14, 82, 3, 0.7], [22, 16, 2, 0.5], [31, 90, 2, 0.6], [38, 7, 3, 0.8], [44, 72, 2, 0.4],
  [4, 52, 2, 0.5], [27, 46, 2, 0.35], [49, 28, 2, 0.5], [17, 33, 2, 0.4], [41, 55, 3, 0.45], [9, 70, 2, 0.6],
];

function ogHtml(iconDataUrl: string, artDataUrl: string, appName: string, description: string, host: string): string {
  const c = OG_COLORS;
  const stars = STARS.map(
    ([left, top, size, opacity]) =>
      `<i style="position:absolute;left:${left}%;top:${top}%;width:${size}px;height:${size}px;border-radius:50%;background:#fff6dc;opacity:${opacity};box-shadow:0 0 ${size * 3}px #fff6dc"></i>`,
  ).join('');
  return `<!doctype html><html lang="vi"><head><style>
${inlinedFontCss('@fontsource/inter/400.css')}
${inlinedFontCss('@fontsource/inter/600.css')}
${inlinedFontCss('@fontsource/cormorant-garamond/700.css')}
</style></head><body style="margin:0">
<div style="position:relative;width:${OG_IMAGE.width}px;height:${OG_IMAGE.height}px;overflow:hidden;color:${c.text};font-family:Inter,sans-serif;background:radial-gradient(ellipse 60% 70% at 18% 20%,${c.violet},transparent 70%),radial-gradient(ellipse 60% 70% at 30% 100%,${c.blue},transparent 70%),${c.deep}">
${stars}
<img src="${artDataUrl}" alt="" style="position:absolute;top:0;right:0;width:${OG_ART_WIDTH}px;height:100%;object-fit:cover;-webkit-mask-image:linear-gradient(to right,transparent,#000 34%)">
<div style="position:absolute;inset:22px;border:1.5px solid ${c.gold};border-radius:28px;opacity:.55"></div>
<div style="position:absolute;inset:30px;border:1px solid ${c.gold};border-radius:22px;opacity:.25"></div>
<div style="position:absolute;top:0;bottom:0;left:0;width:${OG_IMAGE.width - OG_ART_WIDTH + 60}px;box-sizing:border-box;padding:0 30px 0 84px;display:flex;flex-direction:column;justify-content:center;gap:18px">
<div style="width:128px;height:128px;border-radius:50%;padding:5px;background:linear-gradient(145deg,${c.gold},${c.goldDeep} 55%,#8a6526);box-shadow:0 0 40px rgba(236,199,113,.35)"><img src="${iconDataUrl}" width="128" height="128" alt="" style="display:block;width:100%;height:100%;border-radius:50%"></div>
<div style="font-family:'Cormorant Garamond',serif;font-weight:700;font-size:118px;line-height:.95;color:${c.gold};text-shadow:0 0 34px rgba(236,199,113,.35)">${appName}</div>
<div style="font-size:33px;line-height:1.35">${description}</div>
<div style="font-size:26px;font-weight:600;color:${c.muted}"><span style="color:${c.gold}">✦</span> ${host}</div>
</div></div></body></html>`;
}

async function main(): Promise<void> {
  const brand = loadTuviBrand();
  const masterDataUrl = `data:image/png;base64,${readFileSync(MASTER).toString('base64')}`;
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ deviceScaleFactor: 1 });
    const webp512 = await encodeMaster(page, masterDataUrl, 512, 'image/webp');
    writeFileSync(new URL(brand.icon, BRAND_ROOT), iconSvg(webp512, brand.appName));
    writeFileSync(new URL(brand.iconMaskable, BRAND_ROOT), maskableSvg(webp512, TILE, brand.appName));
    writeFileSync(new URL('brand-mark-96.webp', PUBLIC_DIR), dataUrlBytes(await encodeMaster(page, masterDataUrl, 96, 'image/webp')));

    await page.setViewportSize({ width: OG_IMAGE.width, height: OG_IMAGE.height });
    const artDataUrl = `data:image/webp;base64,${readFileSync(OG_ART).toString('base64')}`;
    await page.setContent(ogHtml(webp512, artDataUrl, brand.appName, 'Lập lá số tử vi tiếng Việt theo âm lịch Việt Nam', new URL(primaryOrigin(brand)).host));
    await page.locator('img').evaluateAll((images: HTMLImageElement[]) => Promise.all(images.map((img) => img.decode())));
    await page.evaluate(() => document.fonts.ready);
    writeFileSync(new URL(OG_IMAGE.path, PUBLIC_DIR), await page.screenshot({ clip: { x: 0, y: 0, width: OG_IMAGE.width, height: OG_IMAGE.height } }));
  } finally {
    await browser.close();
  }
  const written = await writeBrandFiles({
    brand,
    root: BRAND_ROOT,
    generatedDir: BRAND_GENERATED_DIR,
    manifests: MANIFEST_OPTIONS,
    indent: 2,
    renderer: chromiumRenderer(chromium),
  });
  console.log(`Wrote brand SVGs, header mark, og-image and ${written.length} files to brand/generated/: ${written.join(', ')}`);
}

main().catch((error: unknown) => {
  console.error('brand:gen failed:', error);
  process.exitCode = 1;
});
